"""Render an otpauth:// URI as an inline SVG QR code (no data: URI, CSP-safe)."""

import qrcode
from markupsafe import Markup
from qrcode.image.svg import SvgPathImage


def svg(uri):
    img = qrcode.make(uri, image_factory=SvgPathImage, box_size=8, border=2)
    out = img.to_string(encoding="unicode")
    start = out.find("<svg")
    return Markup(out[start:] if start >= 0 else out)  # nosec B704: generated by qrcode, no user HTML
